using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace RiseOn.Transitions.Generators {
    /// <summary>
    /// Writes one registry per assembly that references the pack, handing every operation it implements to <c>Operation&lt;TOperation&gt;</c>,<br/>
    /// and marks the assembly with <c>[assembly: OperationRegistry]</c> so it is not scanned at run time.<br/>
    /// The registry is written even when the assembly implements nothing, so the mark is always there.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class OperationRegistryGenerator : IIncrementalGenerator {
        public const string FILE_NAME = "OperationRegistry.g.cs";

        public void Initialize(IncrementalGeneratorInitializationContext context) {
            var registries = context.CompilationProvider.Select(static (compilation, _) => (compilation.AssemblyName, Found: Collect(compilation)));
            context.RegisterSourceOutput(registries, static (output, registry) => {
                if (registry.Found == null) return;

                output.AddSource(FILE_NAME, SourceText.From(Write(registry.AssemblyName, registry.Found), Encoding.UTF8));
            });
        }

        // Null when the compilation does not see the pack; otherwise the fully qualified names of what the registry can create.
        private static ImmutableArray<string>? Collect(Compilation compilation) {
            var operation = compilation.GetTypeByMetadataName(OperationSymbols.OPERATION);
            if (operation == null) return null;

            return OperationSymbols.ListTypes(compilation.Assembly)
                .Where(type => OperationSymbols.ListContracts(type, operation).Count > 0 && OperationSymbols.FindBlocker(type, compilation) == null)
                .Select(type => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .OrderBy(name => name, System.StringComparer.Ordinal)
                .ToImmutableArray();
        }

        // The class is named after its assembly: an assembly that sees the internals of another would otherwise see two of one name.
        private static string Write(string assembly, IEnumerable<string> implementations) {
            var name = "OperationRegistry_" + new string((assembly ?? string.Empty).Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated/>");
            source.AppendLine($"[assembly: global::RiseOn.Transitions.OperationRegistry(typeof(global::RiseOn.Transitions.Generated.{name}))]");
            source.AppendLine();
            source.AppendLine("namespace RiseOn.Transitions.Generated {");
            source.AppendLine("    [global::UnityEngine.Scripting.Preserve]");
            source.AppendLine($"    internal sealed class {name} : global::RiseOn.Transitions.IOperationRegistry {{");
            source.AppendLine("        [global::UnityEngine.Scripting.Preserve]");
            source.AppendLine($"        public {name}() {{ }}");
            source.AppendLine();
            source.AppendLine("        public void Register(global::RiseOn.Transitions.OperationRegistration registration) {");
            foreach (var implementation in implementations) source.AppendLine($"            registration.Add(new {implementation}());");
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }
    }
}